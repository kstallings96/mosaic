/**
 * GENERATES src/data/demoBoard.ts — the board the student watches BIT work.
 *
 * Separate from generateLevels.mjs on purpose. That script owns l1-l3, the
 * three instances the study is built on; rerunning it would replace them.
 * This one adds a board beside them and never touches the file they live in.
 *
 * The board came out of findHeuristicBoards.mjs, which picks for one thing
 * generateLevels.mjs does not: a visible gap between the rules. On this
 * board fewest-first finishes without a single take-back and most-first
 * takes back forty-eight. l1 and l2 are too tight for any of that to show.
 *
 *   node scripts/emitDemoBoard.mjs
 */
import { writeFileSync } from 'node:fs';
import { bestLayout, frame } from './layout.mjs';

/* From findHeuristicBoards.mjs, seed 77001, candidate C. */
const ADJ = [
  [1, 6, 10, 11], [0, 2, 10], [1, 3, 5, 6, 8], [2, 10], [7, 10, 11], [2, 8],
  [0, 2, 7, 8, 9], [4, 6, 8], [2, 5, 6, 7, 9], [6, 8, 11], [0, 1, 3, 4], [0, 4, 9],
];
const GIVEN_AT = [5, 11];
const K = 3;

/** First solution in index order — the same one findHeuristicBoards saw. */
function solve(adj, k) {
  const col = new Array(adj.length).fill(-1);
  let found = null;
  (function go(i) {
    if (found) return;
    if (i === adj.length) { found = [...col]; return; }
    for (let v = 0; v < k; v++) {
      if (adj[i].some((j) => col[j] === v)) continue;
      col[i] = v; go(i + 1); col[i] = -1;
      if (found) return;
    }
  })(0);
  return found;
}

/** Exactly one way to finish, given what is already filled in. */
function completions(adj, k, given, limit = 3) {
  const col = new Array(adj.length).fill(-1);
  for (const [i, v] of Object.entries(given)) col[+i] = v;
  let f = 0;
  (function go(i) {
    if (f >= limit) return;
    if (i === adj.length) { f++; return; }
    if (col[i] !== -1) return go(i + 1);
    for (let v = 0; v < k; v++) {
      if (adj[i].some((j) => col[j] === v)) continue;
      col[i] = v; go(i + 1); col[i] = -1;
      if (f >= limit) return;
    }
  })(0);
  return f;
}

/** How far forced moves alone get, measured the way the levels measure it. */
function propagate(adj, k, given) {
  const col = new Array(adj.length).fill(-1);
  for (const [i, v] of Object.entries(given)) col[+i] = v;
  const dom = (i) => [...Array(k).keys()].filter((v) => !adj[i].some((j) => col[j] === v));
  let placed = 0, waves = 0;
  for (;;) {
    const forced = [...Array(adj.length).keys()].filter((i) => col[i] === -1 && dom(i).length === 1);
    if (!forced.length) break;
    waves++;
    for (const i of forced) { const d = dom(i); if (d.length === 1) { col[i] = d[0]; placed++; } }
  }
  return { placed, waves, left: col.filter((v) => v === -1).length };
}

const solution = solve(ADJ, K);
if (!solution) throw new Error('board C does not colour in 3');

const given = Object.fromEntries(GIVEN_AT.map((i) => [i, solution[i]]));
const unique = completions(ADJ, K, given);
if (unique !== 1) throw new Error(`board C has ${unique} completions, not 1`);

const pr = propagate(ADJ, K, given);

const drawing = bestLayout(ADJ);
if (!drawing) throw new Error('no readable layout for board C');

const board = {
  id: 'demo',
  title: 'How BIT works it out',
  rule: 'Crates that touch can’t hold the same animal.',
  note: 'Same rule as before. This time you pick how BIT decides where to work.',
  words: { thing: 'crate', slot: 'animal' },
  icons: 'animals',
  kind: 'graph',
  k: K,
  nodes: drawing.pos,
  adj: ADJ,
  given,
  solution,
  view: frame(drawing.pos, 34),
  stats: {
    regions: ADJ.length,
    waves: pr.waves,
    forced: pr.placed,
    choices: pr.left,
  },
};

const edges = ADJ.reduce((a, b) => a + b.length, 0) / 2;
console.log(
  `demo: ${ADJ.length} crates, ${edges} touching pairs, ${drawing.c} line crossings ` +
    `(best of 160 layouts), closest pair ${Math.round(drawing.gapAfter)}, ` +
    `${GIVEN_AT.length} filled in, unique completion, propagation places ` +
    `${pr.placed} in ${pr.waves} waves and stalls with ${pr.left}`,
);

writeFileSync(
  'src/data/demoBoard.ts',
  `/**
 * GENERATED by scripts/emitDemoBoard.mjs — do not hand-edit.
 *
 * The board the student watches rather than plays. It is not one of the
 * three study levels and is deliberately not in LEVELS: verifyLevels.mjs
 * checks that ladder for a difficulty progression this board has no place
 * in, and l1-l3 must stay exactly as they were verified.
 *
 * What makes it the right board is a property the study levels were never
 * selected for — the choice of search rule has to visibly change how much
 * work the solver does. On l1 and l2 it does not: both are tight enough
 * that every systematic order finishes with no backtracking at all. Here,
 * working where the fewest animals fit finishes in 10 moves with nothing
 * taken back, and working where the most fit needs 58 moves and 48
 * take-backs. Same board, same machine, different rule.
 */

import type { ColourLevel } from './levels';

export const DEMO_BOARD: ColourLevel = ${JSON.stringify(board, null, 2)
    .split('\n')
    .map((l, i) => (i === 0 ? l : '  ' + l))
    .join('\n')} as ColourLevel;
`,
);
console.log('wrote src/data/demoBoard.ts');
